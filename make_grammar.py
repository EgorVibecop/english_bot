def main():
    existing = json.load(open(OUT, encoding="utf-8"))

    # У упражнений на времена темы ещё не было — проставляем.
    for item in existing:
        item.setdefault("topic", "tenses")
        item.setdefault("topic_ru", "Времена")

    kept = [e for e in existing if e.get("topic") == "tenses"]
    seen = {e["sentence"] for e in kept}

    added = 0
    for topic, topic_ru, items in TOPICS:
        for rule, explanation, sentence, answers, translation in items:
            if sentence in seen:
                continue
            seen.add(sentence)
            kept.append({
                "tense": rule,
                "tense_ru": explanation,
                "topic": topic,
                "topic_ru": topic_ru,
                "sentence": sentence,
                "answers": answers,
                "translation": translation,
            })
            added += 1

    json.dump(kept, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, indent=2)

    import collections
    by_topic = collections.Counter(e["topic_ru"] for e in kept)
    print(f"Упражнений всего: {len(kept)} (добавлено {added})")
    for name, count in by_topic.most_common():
        print(f"   {name}: {count}")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    main()
